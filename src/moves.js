  // 当前这一招（收招阶段 cur 已经清空，靠 engine 记的 last 接上）
  function activeKey(e) {
    if (!e) return null;
    if (e.state === 'recover') return e.last && e.last.key;
    return e.cur && e.cur.key;
  }

  // 出招进度 0..1；不在出招时返回 -1
  function moveP(e, t) {
    if (!e) return -1;
    if (e.state === 'windup') return clamp01(e.tele || 0) * 0.5;
    if (e.state === 'active') return 0.5 + clamp01(e.actK || 0) * 0.26;
    if (e.state === 'recover') {
      const len = Math.max(1, e.recLen || 400);
      return 0.76 + 0.24 * clamp01(((t || 0) - (e.recStart || 0)) / len);
    }
    return -1;
  }

  function foeSample(e, t, tbl, base) {
    const p = moveP(e, t);
    if (p < 0) return base;
    const key = activeKey(e);
    const row = (key && tbl[key]) || tbl._any;
    if (!row) return base;
    const out = {};
    for (const k in row) {
      if (k === 't') continue;
      out[k] = kf(p, frames6(row[k]));
    }
    return Object.assign({}, base, out);
  }

